// -----------------------------------------------------------------------------
// Minimal UPnP / IGD SOAP transport (no runtime dependency).
//
// Why hand-rolled: an IGD box nests the WAN services (WANCommonInterfaceConfig,
// WANIPConnection/WANPPPConnection) several levels deep inside `<deviceList>`
// sub-devices, and we need services from two different sub-devices. The popular
// npm UPnP libraries either only parse the root device's services or hardcode
// the WAN*Connection service — none reach the byte/packet counters. So we do
// the two simple things ourselves: parse the description tree, and POST SOAP.
//
// The XML here is small and machine-generated by the box, so lightweight regex
// extraction is enough (and namespace-prefix tolerant); we never build a full
// DOM.
// -----------------------------------------------------------------------------

import { REQUEST_TIMEOUT } from '../constants.js';

/**
 * Read the inner text of the first `<tag>…</tag>` (any namespace prefix),
 * trimmed. Returns undefined when the tag is absent.
 * @param {string} xml
 * @param {string} tag local tag name, e.g. 'NewExternalIPAddress'
 * @returns {string|undefined}
 */
export function extractTag(xml, tag) {
  const match = new RegExp(
    `<(?:[\\w-]+:)?${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</(?:[\\w-]+:)?${tag}>`,
  ).exec(xml);
  return match ? match[1].trim() : undefined;
}

/**
 * Turn a possibly-relative URL from the description into an absolute one.
 * @param {string} base URLBase or the description URL
 * @param {string} url controlURL / SCPDURL value
 * @returns {string}
 */
export function toAbsoluteUrl(base, url) {
  if (!url) {
    return url;
  }
  try {
    return new URL(url, base).toString();
  } catch {
    return url;
  }
}

/**
 * GET a URL and return the body as text, with a timeout.
 * @param {string} url
 * @returns {Promise<string>}
 */
export async function fetchText(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT);
  try {
    const response = await fetch(url, { signal: controller.signal });
    if (!response.ok) {
      throw new Error(`GET ${url} failed with HTTP ${response.status}`);
    }
    return await response.text();
  } finally {
    clearTimeout(timer);
  }
}

/**
 * Parse an IGD root device description. Walks the WHOLE device tree (not just
 * the root device) so the nested WAN services are found, and returns each
 * service keyed by its serviceType with an absolute controlURL.
 * @param {string} xml the rootDesc.xml body
 * @param {string} descriptionUrl the URL it was fetched from (for base)
 * @returns {{ friendlyName: string|null, udn: string|null, services: Array<{ serviceType: string, controlURL: string }> }}
 */
export function parseDescription(xml, descriptionUrl) {
  // <URLBase> (optional) overrides the description URL for relative paths.
  const urlBase = extractTag(xml, 'URLBase') || descriptionUrl;

  // The first friendlyName / UDN in the document belong to the root device.
  const friendlyName = extractTag(xml, 'friendlyName') || null;
  const udn = extractTag(xml, 'UDN') || null;

  const services = [];
  const serviceRegex = /<service>([\s\S]*?)<\/service>/g;
  let match;
  while ((match = serviceRegex.exec(xml)) !== null) {
    const block = match[1];
    const serviceType = extractTag(block, 'serviceType');
    const controlURL = extractTag(block, 'controlURL');
    if (serviceType && controlURL) {
      services.push({
        serviceType,
        controlURL: toAbsoluteUrl(urlBase, controlURL),
      });
    }
  }

  return { friendlyName, udn, services };
}

/**
 * Call a SOAP action and return the response body XML.
 * @param {string} controlURL absolute control URL
 * @param {string} serviceType full serviceType urn
 * @param {string} action action name
 * @param {Record<string, string|number>} [args] input arguments
 * @returns {Promise<string>} the raw response XML (parse outputs with extractTag)
 */
export async function callSoap(controlURL, serviceType, action, args = {}) {
  const envelope =
    '<?xml version="1.0" encoding="utf-8"?>' +
    '<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"' +
    ' s:encodingStyle="http://schemas.xmlsoap.org/soap/encoding/">' +
    '<s:Body>' +
    `<u:${action} xmlns:u="${serviceType}">` +
    Object.entries(args)
      .map(([name, value]) => `<${name}>${value ?? ''}</${name}>`)
      .join('') +
    `</u:${action}>` +
    '</s:Body></s:Envelope>';

  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT);
  try {
    const response = await fetch(controlURL, {
      method: 'POST',
      headers: {
        'Content-Type': 'text/xml; charset="utf-8"',
        SOAPACTION: `"${serviceType}#${action}"`,
      },
      body: envelope,
      signal: controller.signal,
    });
    const text = await response.text();
    if (!response.ok) {
      const errorCode = extractTag(text, 'errorCode');
      const errorDescription = extractTag(text, 'errorDescription');
      throw new Error(
        `SOAP ${action} failed (HTTP ${response.status}` +
          (errorCode ? `, UPnP ${errorCode} ${errorDescription || ''}` : '') +
          ')',
      );
    }
    return text;
  } finally {
    clearTimeout(timer);
  }
}
